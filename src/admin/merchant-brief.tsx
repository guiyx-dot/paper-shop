import { useState } from 'react'

export function MerchantBrief() {
  const [open, setOpen] = useState(false)
  const classes = ['phase2-brief', 'is-dock', open ? 'is-open' : 'is-shut'].filter(Boolean).join(' ')
  return (
    <aside className={classes}>
      <button className="phase2-toggle" type="button" aria-expanded={open} onClick={() => setOpen((value) => !value)}>
        <span>说明</span>
        <i>{open ? '收起' : '展开'}</i>
      </button>
      {open ? (
        <div className="phase2-body">
          <p className="phase2-kicker">商户平台改造</p>
          <p className="phase2-lead">给研发看。标了演示数据的，按演示数字做，不换成正式费率。</p>

          <h3>1. 审批记录的场景</h3>
          <ul>
            <li>一级页签顺序：事故车场景、会员营销、新车场景、积分权益、二手车场景。</li>
            <li>二级名称里，只有事故车仍叫事故车佣金。其余是维修权益、会员营销权益、新车权益、二手车权益。会员营销下面还有一条不带「权益」的会员营销。</li>
            <li>佣金场景按这五条判断，不看名字里有没有「佣金」：事故车佣金、维修权益、会员营销权益、新车权益、二手车权益。</li>
          </ul>

          <h3>2. 权益下单</h3>
          <ul>
            <li>不再用弹窗，进入独立页面，标题是采购积分。</li>
            <li>专用券和通用积分在同一页。上面选类型，下面跟着变。进来默认专用券。</li>
            <li>专用券下面的分类是通用币、通用券。点具体商品，或点通用积分那一项，直接进入付款页。</li>
            <li>通用币两款：微信通用币、支付宝通用币。原来的通用金改叫通用币。</li>
            <li>通用券五款：微信立减金、支付宝通用券、支付宝通用券Plus、因公付、万佳乐。专用券的说明是：兑换「权益专区」币/券。</li>
            <li>通用积分只有这一项商品。</li>
            <li>佣金场景只能选通用积分，不出现专用券，也不出现币和券。</li>
          </ul>

          <h3>3. 付款</h3>
          <ul>
            <li>点确认支付先确认服务费。演示数据：本次费率由 7% 调整为 8%，不同意就不能提交。</li>
            <li>按钮是拒绝、接受。拒绝留在付款页，接受后才支付。</li>
            <li>支付完成后进入发放订单。</li>
            <li>付款页和发放订单里，查看入口都叫查看发放信息。弹窗标题仍是账号信息。</li>
            <li>原来的手续费都改叫服务费，费率按百分比展示。</li>
          </ul>

          <h3>4. 发放订单</h3>
          <ul>
            <li>放在商品管理下，菜单名是发放订单。数字中台商城里的商品订单不改。</li>
            <li>列表去掉商户 ID、折扣、奖励费用、转出费率。</li>
            <li>状态分成待支付、充值中、发放成功、发放失败。发放成功再分全部发放成功、部分成功。</li>
            <li>金额下面展示商品费用和服务费，服务费率单独一列。</li>
            <li>发放状态后面有领取状态，并带有效期。有效期最长 90 天，可以标已过期。</li>
            <li>发放成功的操作只有详情，进入明细数据。发放失败可以下载报错信息。撤回和补发不在这张列表上。</li>
          </ul>

          <h3>5. 明细数据的撤回和补发</h3>
          <ul>
            <li>撤回要确认：撤回后对应卡券或商品不再可用，并退款给商户。退款不包含服务费。</li>
            <li>不能撤回、不能补发，用同一类提示。</li>
            <li>补发要核对发放商品和发放金额，补发原因必填。每条数据只能补发一次，补过再点会提示。</li>
            <li>可以换商品。可选通用币、通用券里的商品，以及通用积分。</li>
            <li>新商品价格更高，或服务费率更高，先做补差支付，付完才算补发成功。两项都没有更高，确认后直接补发。</li>
            <li>补差只算涨出的部分。商品补差取价格差额，服务费补差取服务费差额，应付是这两项相加。降下来的部分不退。差额是 0 时仍进入补差支付。</li>
            <li>演示数据：万佳乐价格 100，其余专用商品价格 1，专用服务费 8%，通用积分服务费 3%。</li>
          </ul>

          <h3>6. 审批记录的可见字段</h3>
          <ul>
            <li>设置可见字段可以勾选后才展示，并记住上一次的选择。至少留一个字段。</li>
            <li>进来默认只显示这 14 个：批次号、审批单号、商户、审批链名称、关联凭证、凭证审核状态、审批状态、商品名称、发放金额、领取人手机号、领取人姓名、领取人身份证号、商品订单号、下单状态。其余默认不勾选。</li>
          </ul>

          <h3>7. 进入商户平台</h3>
          <ul>
            <li>每次进入都有商品平台调价通知。必须勾选「我已阅读并确认上述调价」，才能点我知道了关掉。</li>
            <li>演示数据：支付宝通用金（营销折让），服务费由低于 8% 调整为 8%，2026 年 8 月 15 日 0 点起。</li>
          </ul>
        </div>
      ) : null}
    </aside>
  )
}
